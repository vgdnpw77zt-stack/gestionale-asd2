def organization_jsonld(c):
    """BodyMind is one ASD using partner venues, not two invented business branches."""
    places=[]
    for venue in c.get("venues", [])[:2]:
        if not venue.get("name") or not venue.get("address"):
            continue
        places.append({
          "@type":"Place",
          "name":venue["name"] + " — sede corsi BodyMind",
          "address":{"@type":"PostalAddress","streetAddress":venue["address"].split(",")[0],
                     "addressLocality":"Aprilia","addressRegion":"LT","addressCountry":"IT"}
        })
    result={
      "@context":"https://schema.org",
      "@type":"SportsOrganization",
      "@id":ORIGIN+"/#organizzazione",
      "name":"BodyMind Aerial Studio ASD",
      "alternateName":"BodyMind Aerial Studio",
      "url":ORIGIN+"/",
      "logo":ORIGIN+"/seed-media/logo?v=9",
      "description":"Associazione sportiva dilettantistica di danza aerea, cerchio aereo e tessuti ad Aprilia.",
      "sameAs":["https://www.instagram.com/bodymind.aerialstudio/"],
      "areaServed":{"@type":"City","name":"Aprilia"},
      "knowsAbout":["Danza aerea","Cerchio aereo","Aerial hoop","Tessuti aerei",
                    "Discipline aeree","Danza acrobatica aerea"],
      "contactPoint":{"@type":"ContactPoint","contactType":"informazioni sui corsi",
                      "telephone":"+39 351 518 7943","availableLanguage":"it"}
    }
    if places: result["location"]=places
    return result

def page_jsonld(page,c):
    org=organization_jsonld(c)
    slug=page["slug"]
    url=ORIGIN+"/"+slug
    webpage={"@type":"WebPage","@id":url+"#webpage","url":url,"name":page["title"],
             "description":page["description"],"inLanguage":"it-IT",
             "about":{"@id":ORIGIN+"/#organizzazione"}}
    breadcrumb={"@type":"BreadcrumbList","@id":url+"#breadcrumb","itemListElement":[
        {"@type":"ListItem","position":1,"name":"Home","item":ORIGIN+"/"},
        {"@type":"ListItem","position":2,"name":page["h1"],"item":url}
    ]}
    return {"@context":"https://schema.org","@graph":[
       {k:v for k,v in org.items() if k!="@context"},webpage,breadcrumb
    ]}
